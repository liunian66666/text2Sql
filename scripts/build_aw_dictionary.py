def _clean(value: object) -> str:
    text = str(value or "").strip()
    return text if text else UNKNOWN


def _origin(has_value: bool, *, upstream: bool) -> str:
    if upstream:
        return "upstream_description" if has_value else "unknown"
    return "model_candidate" if has_value else "unknown"


def _table_ref(name: str) -> str:
    return f"data/adventureworks/provider-schema.json#tables[name={name}]"


def build() -> dict:
    if not PROVIDER.is_file():
        raise FileNotFoundError(f"Missing provider metadata: {PROVIDER}")
    if not DATABASE.is_file():
        raise FileNotFoundError(f"Missing AdventureWorks SQLite: {DATABASE}")

    provider = json.loads(PROVIDER.read_text(encoding="utf-8"))
    provider_tables = {t["name"]: t for t in provider["tables"] if t.get("kind") == "table"}

    with closing(sqlite3.connect(f"file:{DATABASE.as_posix()}?mode=ro", uri=True)) as conn:
        real_names = list_tables(conn)
        real_tables = {name: read_table(conn, name) for name in real_names}

    missing = sorted(set(real_names) - set(provider_tables))
    extra = sorted(set(provider_tables) - set(real_names))
    if missing or extra:
        raise SystemExit(f"Provider/SQLite table mismatch: missing={missing} extra={extra}")

    tables: list[dict] = []
    total_columns = upstream_columns = zh_tables = zh_columns = alias_columns = 0
    for name in real_names:
        raw = real_tables[name]
        pt = provider_tables[name]
        upstream_desc = {c["name"]: _clean(c.get("description")) for c in pt.get("columns", [])}
        curated_table = CURATED_TABLES.get(name, {})
        curated_cols = CURATED_COLUMNS.get(name, {})
        zh_table = _clean(curated_table.get("zh"))
        table_aliases = sorted(set(str(a) for a in curated_table.get("aliases", [])))
        if zh_table != UNKNOWN:
            zh_tables += 1

        columns = []
        for column in raw.columns:
            en = upstream_desc.get(column.name, UNKNOWN)
            if en == UNKNOWN:
                # A provider column absent from the real DB is a contract error;
                # a real column absent from provider stays UNKNOWN (no invention).
                pass
            curated = curated_cols.get(column.name, {})
            zh = _clean(curated.get("zh"))
            aliases = sorted(set(str(a) for a in curated.get("aliases", [])))
            total_columns += 1
            upstream_columns += int(en != UNKNOWN)
            zh_columns += int(zh != UNKNOWN)
            alias_columns += int(bool(aliases))
            columns.append({
                "column_id": f"{DATABASE_ID}.{name}.{column.name}",
                "column_name": column.name,
                "data_type_real": column.data_type or UNKNOWN,
                "primary_key": column.primary_key_position > 0,
                "description_en": en,
                "description_zh": zh,
                "aliases": aliases,
                "origin": {
                    "description_en": _origin(en != UNKNOWN, upstream=True),
                    "description_zh": _origin(zh != UNKNOWN, upstream=False),
                    "aliases": _origin(bool(aliases), upstream=False),
                    "data_type_real": "database_fact",
                },
                "review_status": "unreviewed",
                "source_ref": f"{_table_ref(name)}.columns[name={column.name}]",
            })
        tables.append({
            "table_id": f"{DATABASE_ID}.{name}",
            "table_name": name,
            "primary_keys_real": sorted(
                (c.name for c in raw.columns if c.primary_key_position > 0),
                key=lambda cname: next(c.primary_key_position for c in raw.columns if c.name == cname),
            ),
            "description_en": _clean(pt.get("description")),
            "description_zh": zh_table,
            "aliases": table_aliases,
            "origin": {
                "description_en": _origin(bool(_clean(pt.get("description")) != UNKNOWN), upstream=True),
                "description_zh": _origin(zh_table != UNKNOWN, upstream=False),
                "aliases": _origin(bool(table_aliases), upstream=False),
                "primary_keys_real": "database_fact",
            },
            "review_status": "unreviewed",
            "source_ref": _table_ref(name),
            "columns": columns,
        })

    source = provider.get("source", {})
    return {
        "database_id": DATABASE_ID,
        "schema_version": "1",
        "source": {
            "upstream_repository": source.get("repository"),
            "upstream_revision": source.get("revision"),
            "upstream_installer": source.get("path"),
            "upstream_version": source.get("version"),
            "license": source.get("license"),
            "provider_file": str(PROVIDER.relative_to(ROOT).as_posix()),
            "provider_sha256": hashlib.sha256(PROVIDER.read_bytes()).hexdigest(),
            "sqlite_sha256": hashlib.sha256(DATABASE.read_bytes()).hexdigest(),
            "origin_note": (
                "英文描述逐字取自已下载的 provider 元数据 description 字段，该元数据锁定官方 commit；"
                "未逐条与 SQL Server 扩展属性 MS_Description 原文比对，故标 upstream_description 而非 official_reviewed。"
                "中文语义与业务别名按 表+列 显式枚举，由模型起草，标 model_candidate / unreviewed，"
                "不是微软官方业务规则，也未通过人工审核。"
            ),
        },
        "counts": {
            "tables_total": len(tables),
            "tables_with_upstream_en": sum(t["description_en"] != UNKNOWN for t in tables),
            "tables_with_zh_candidate": zh_tables,
            "tables_with_aliases": sum(bool(t["aliases"]) for t in tables),
            "columns_total": total_columns,
            "columns_with_upstream_en": upstream_columns,
            "columns_with_zh_candidate": zh_columns,
            "columns_with_aliases": alias_columns,
            "columns_unknown_en": total_columns - upstream_columns,
        },
        "tables": sorted(tables, key=lambda item: item["table_name"]),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=str(OUTPUT))
    parser.add_argument("--validate-only", action="store_true")
    args = parser.parse_args()
    payload = build()
    counts = payload["counts"]
    if counts["tables_total"] != 71 or counts["columns_total"] != 486:
        raise SystemExit(f"Unexpected real schema size: {counts}")
    if not args.validate_only:
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                          encoding="utf-8")
    print(json.dumps({"validated_only": args.validate_only, "output": str(args.output),
                      "counts": counts}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
