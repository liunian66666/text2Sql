"""Build the AdventureWorks schema dictionary from *already downloaded* upstream metadata.

Sources of truth (both pinned in docs/adventureworks/PROVENANCE.md):

1. ``data/adventureworks/provider-schema.json`` — the converter contract shipped with
   the SQLite port. It declares the upstream Microsoft commit ``beaab06...`` and the
   installer ``oltp-install-script/instawdb.sql``. Its ``description`` fields are
   upstream metadata text; we keep them verbatim in English.
2. The real SQLite file — table/column existence, types and primary keys are
   verified with PRAGMA. A provider entry that does not exist in the real DB is
   rejected, never silently accepted.

Chinese semantic descriptions and business aliases are *curated by table+column*,
never generated by splitting a column name across the whole database. They are
tagged ``origin=model_candidate`` and ``review_status=unreviewed``: they are NOT
official Microsoft text and NOT human-reviewed. Where upstream description is
missing the value stays the explicit sentinel UNKNOWN.

Usage:
    python scripts/build_aw_dictionary.py
    python scripts/build_aw_dictionary.py --validate-only
"""
